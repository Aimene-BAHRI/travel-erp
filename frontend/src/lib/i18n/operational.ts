export function useOperationalText() {
  const { locale } = useLocale();
  return (text: string) => locale === "ar" ? (translations[text] ?? text) : (english[text] ?? text);
}

const translations = { ...sidebarArabic, ...arabic };
const english = Object.fromEntries(Object.entries(translations).map(([en, ar]) => [ar, en]));
